  fun categoryLabel(raw: String): String =
    when (raw.trim().lowercase()) {
      "all" -> allCategoryLabel
      "love" -> loveCategoryLabel
      "attitude" -> attitudeCategoryLabel
      "motivation", "motivational" -> motivationCategoryLabel
      "sad" -> sadCategoryLabel
      "dosti", "friendship" -> friendshipCategoryLabel
      else -> raw
    }

  private val allCategoryLabel: String
    get() =
      when (tabHome) {
        "होम" -> "सभी"
        "ہوم" -> "سب"
        else -> "All"
      }

  private val loveCategoryLabel: String
    get() =
