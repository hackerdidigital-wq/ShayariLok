val LocalAppStrings = staticCompositionLocalOf { englishStrings() }

fun appStringsFor(languageCode: String): AppStrings =
  when (languageCode.trim().lowercase()) {
    "hi" -> hindiStrings()
    "ur", "ar", "fa" -> urduStrings()
    else -> englishStrings()
  }

